#!/usr/bin/env bash
# Publish an OTA update (docs/recipes/over-the-air-updates.md) for Airwave.
#
#   bash scripts/publish-ota.sh            # full deploy: classify + publish streams
#   bash scripts/publish-ota.sh --dry      # classify only, write nothing
#
# Two invariants that cost an afternoon to learn (docs/04-build-log.md §54):
#
# 1. The seed must be FILLED for `deploy`, matching the state the genesis
#    binaries were built in (scripts/build-native.sh fills the same way).
#    The compatibility id hashes `typescriptModule` — the app.ts module
#    hash, which includes data/globe-seed.ts — so a deploy captured with
#    the empty seed starts streams the installed binaries will never fetch.
#
# 2. The 30MB+ release records (origin/.exact/prod/<id>/releases/*.json)
#    never go to Cloudflare Pages: the 25 MiB per-file cap fails the whole
#    deployment. publish-web.sh already strips them when it syncs
#    origin/.exact -> web/updates/.exact (clients only fetch exact.json + blobs).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
source "$ROOT/.tools/env.sh"
export EXACT_SIGNING_KEY_DIR="${EXACT_SIGNING_KEY_DIR:-$ROOT/.tools/keys}"

SEED="airwave/data/globe-seed.ts"
SNAPSHOT=".research/geo/globe-seed.full.ts"

[ -f "$SNAPSHOT" ] || { echo "no seed snapshot at $SNAPSHOT — run scripts/snapshot-globe.sh first" >&2; exit 1; }
[ -d "$ROOT/.tools/keys" ] || { echo "no signing keys in $ROOT/.tools/keys — see §54 keygen" >&2; exit 1; }

restore() { printf '%s\n' "// GENERATED by scripts/snapshot-globe.sh — do not edit by hand.
// git keeps this empty; scripts/build-native.sh fills it before native builds.
export const GLOBE_SEED = [];" > "$SEED"; }
trap restore EXIT

cp "$SNAPSHOT" "$SEED"
echo "seed filled: $(wc -c < "$SEED") bytes"

cd airwave
if [ "${1:-}" = "--dry" ]; then
  bun exact.mjs deploy --dirty --origin ../origin
else
  bun exact.mjs deploy --dirty --origin ../origin --yes
fi
cd "$ROOT"

echo
echo "Next: bash scripts/publish-web.sh  (syncs web/ + web/updates/), then commit + push."
