#!/usr/bin/env bash
# Build the NATIVE apps (macOS / iOS / Android) with the globe seed embedded.
#
# The seed file is empty in git (web builds never carry it); this script fills
# it from the snapshot, builds, and restores the empty default afterwards.
# Usage: scripts/build-native.sh [mac|ios|android|all]
set -euo pipefail
cd "$(dirname "$0")"
ROOT="$(cd .. && pwd)"
# Secrets live outside git (.tools/ is gitignored); the Maps key is read at
# build time through app.json's {"env": "..."} indirection, never committed.
[ -f "$ROOT/.tools/secrets.sh" ] && . "$ROOT/.tools/secrets.sh"
cd "$ROOT/airwave"

TARGET="${1:-all}"
SEED="data/globe-seed.ts"
FULL="../.research/geo/globe-seed.full.ts"
EMPTY="// GENERATED by scripts/snapshot-globe.sh — do not edit by hand.
// git keeps this empty; scripts/build-native.sh fills it before native builds.
export const GLOBE_SEED = [];"

restore() {
  printf '%s\n' "$EMPTY" > "$SEED"
  # The freshness check compares mtimes; keep the built artifacts newer than the seed.
  find "$ROOT/airwave/target" -name 'app-release.apk' -newermt '@1' -exec touch {} + 2>/dev/null || true
}
trap restore EXIT

if [ ! -s "$FULL" ]; then
  echo "No seed snapshot at $FULL — run scripts/snapshot-globe.sh first." >&2
  exit 1
fi
cp "$FULL" "$SEED"
echo "Seed filled: $(wc -c < "$SEED") bytes."

source ../.tools/env.sh

# OTA: every native binary carries the update store (deploy.store = "A" in
# app.json) and production trust. EXACT_UPDATE_GENESIS=1 embeds sequence zero
# of the "prod" stream; a binary rebuilt after releases exist can instead pass
# EXACT_UPDATE_RECEIPT=<origin>/.exact/prod/<compat>/releases/<release>.json.
case "$TARGET" in
  mac)    EXACT_UPDATE_GENESIS=1 bun exact.mjs mac --release ;;
  ios)    EXACT_UPDATE_GENESIS=1 bun exact.mjs ios --release ;;
  android) JAVA_HOME="/Applications/Android Studio.app/Contents/jbr/Contents/Home" \
           EXACT_UPDATE_TRUST=production EXACT_UPDATE_GENESIS=1 \
           bun exact.mjs android --release ;;
  all)    echo "build one platform at a time: mac | ios | android" >&2; exit 2 ;;
  *)      echo "unknown target $TARGET" >&2; exit 2 ;;
esac
