#!/usr/bin/env bash
# Fill airwave/data/globe-seed.ts with the full geo-tagged station set.
#
# The seed ships ONLY in native builds (see scripts/build-native.sh); the web
# build never carries it, and git keeps the empty default so the repo stays
# small. Run with no arguments to refresh .research/geo/globe-seed.full.ts.
set -euo pipefail
cd "$(dirname "$0")/.."

OUT=".research/geo/globe-seed.full.ts"
CACHE="/tmp/geo-12k.json"
SRC=""
if [ -s "$CACHE" ]; then
  SRC="$CACHE"
else
  echo "Fetching the full geo set from radio-browser (three pages)…" >&2
  rm -f /tmp/geo-seed-a.json /tmp/geo-seed-b.json /tmp/geo-seed-c.json
  curl -sS -H 'User-Agent: Airwave/0.1 (Exact; radio-browser client)' \
    'https://de1.api.radio-browser.info/json/stations/search?limit=4000&offset=0&order=votes&reverse=true&has_geo_info=true&hidebroken=true&is_https=true' -o /tmp/geo-seed-a.json
  curl -sS -H 'User-Agent: Airwave/0.1 (Exact; radio-browser client)' \
    'https://de1.api.radio-browser.info/json/stations/search?limit=4000&offset=4000&order=votes&reverse=true&has_geo_info=true&hidebroken=true&is_https=true' -o /tmp/geo-seed-b.json
  curl -sS -H 'User-Agent: Airwave/0.1 (Exact; radio-browser client)' \
    'https://de1.api.radio-browser.info/json/stations/search?limit=4000&offset=8000&order=votes&reverse=true&has_geo_info=true&hidebroken=true&is_https=true' -o /tmp/geo-seed-c.json
  SRC="/tmp/geo-seed-a.json"  # the pages are merged below
fi

mkdir -p .research/geo
python3 - "$SRC" "$OUT" <<'EOF'
import json, sys, os

srcs = ['/tmp/geo-seed-a.json', '/tmp/geo-seed-b.json', '/tmp/geo-seed-c.json']
rows = []
if len(sys.argv) > 1 and os.path.exists(sys.argv[1]) and sys.argv[1] not in srcs:
    rows = json.load(open(sys.argv[1]))
else:
    for p in srcs:
        if os.path.exists(p):
            rows += json.load(open(p))

seen, out = set(), []
for r in rows:
    uuid = r.get('stationuuid') or ''
    stream = r.get('url_resolved') or r.get('url') or ''
    lat, lon = r.get('geo_lat'), r.get('geo_long')
    if not uuid or not stream.startswith('https://'): continue
    # A live ${…} or backtick in a URL is a JS-injection the seed literal would run.
    if '${' in stream or '`' in stream or '${' in (r.get('name') or ''): continue
    if not isinstance(lat, (int, float)) or not isinstance(lon, (int, float)): continue
    if isinstance(r.get('hls'), (int, float)) and r['hls'] != 0: continue
    if '.m3u8' in stream.lower() or '.m3u' in stream.lower() or '.pls' in stream.lower(): continue
    if uuid in seen: continue
    seen.add(uuid)
    tag = (r.get('tags') or '').split(',')[0].strip()
    out.append([
        uuid,
        (r.get('name') or '').strip()[:64],
        stream[:180],
        round(float(lat), 3),
        round(float(lon), 3),
        (r.get('favicon') if (r.get('favicon') or '').startswith('https://') else '')[:120],
        (r.get('codec') or '').upper()[:8],
        int(r.get('bitrate') or 0),
        (r.get('countrycode') or '')[:2],
        tag[:24],
        int(r.get('votes') or 0),
    ])

payload = json.dumps(out, separators=(',', ':'), ensure_ascii=False)
# A JS array literal, not a string: a template literal would evaluate the JSON's
# backslash escapes and quietly corrupt the data.
js = (
    '// GENERATED by scripts/snapshot-globe.sh — do not edit by hand.\n'
    '// git keeps this empty; scripts/build-native.sh fills it before native builds.\n'
    'export const GLOBE_SEED = %s;\n' % ("[]" if not out else payload)
)
open(sys.argv[2], 'w').write(js)
print('stations', len(out), 'bytes', len(payload), '→', sys.argv[2])
EOF
